import { readFileSync, writeFileSync } from 'node:fs';
const palettes=JSON.parse(readFileSync(new URL('../data/palettes.json',import.meta.url),'utf8'));
function luminance(hex){
  const rgb=hex.match(/[a-f\d]{2}/gi).map(c=>parseInt(c,16)/255).map(c=>c<=.04045?c/12.92:((c+.055)/1.055)**2.4);
  return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722;
}
function contrast(a,b){const x=luminance(a),y=luminance(b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);}
const ids=new Set();
for(const p of palettes){
  if(ids.has(p.id)||!/^[-a-z]+$/.test(p.id))throw Error('Invalid palette ID');ids.add(p.id);
  for(const color of Object.values(p.colors))if(!/^#[a-f\d]{6}$/i.test(color))throw Error('Invalid color in '+p.id);
  for(const key of ['ink','body','muted','accent'])if(contrast(p.colors[key],p.colors.reader)<4.5)throw Error(p.id+': insufficient reader contrast for '+key);
  if(contrast(p.colors.onAccent,p.colors.accent)<4.5)throw Error(p.id+': insufficient selected marker contrast');
}
const css=palettes.map(p=>`:root[data-palette="${p.id}"]{\n${Object.entries(p.colors).map(([k,v])=>`  --p-${k}:${v};`).join('\n')}\n  --p-map-blend:${p.map.blend};--p-map-filter:${p.map.filter};--p-map-opacity:${p.map.opacity};--p-symbol-filter:${p.map.symbol};\n}`).join('\n');
writeFileSync(new URL('../dist/palette-tokens.css',import.meta.url),'/* Generated by scripts/build-palettes.mjs. */\n'+css+'\n');
writeFileSync(new URL('../dist/palette-options.js',import.meta.url),'window.TERRA_PALETTES='+JSON.stringify(palettes)+';\n');
console.log('Four palettes validated: body, secondary text, accents and selected labels meet 4.5:1 contrast on their solid surfaces.');
